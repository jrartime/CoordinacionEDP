-- ============================================================================
-- RD 723/2026: periodos de actividad de los contratos de servicio (esquema `coordinacion`).
--
-- Para el personal fijo-discontinuo, el anexo informativo debe decir los periodos de actividad e
-- inactividad (art. 3.2.g.5.iii) o su estimación. Se guardan en el contrato administrativo en el
-- que trabaja la persona (el de sus actividades): una fila por tramo de actividad. La inactividad
-- es el resto del tiempo entre tramos. La jornada anual estimada del anexo sale de la jornada
-- semanal por las semanas de actividad.
--
-- También fija el lugar de consulta de los documentos que cita el anexo (apartado 13): la sede de
-- la empresa, igual para todo el personal.
-- ============================================================================

create table if not exists coordinacion.contratos_periodos_actividad (
  id bigint generated by default as identity primary key,
  contrato_id integer not null references coordinacion.contratos (id) on delete cascade,
  fecha_inicio date not null,
  fecha_fin date not null,
  notas text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint contratos_periodos_actividad_fechas check (fecha_fin >= fecha_inicio)
);

create index if not exists contratos_periodos_actividad_contrato_idx
  on coordinacion.contratos_periodos_actividad (contrato_id, fecha_inicio);

comment on table coordinacion.contratos_periodos_actividad is
  'Tramos de actividad de un contrato de servicio con personal fijo-discontinuo. Alimenta el anexo informativo RD 723/2026 (periodos de actividad e inactividad y jornada anual estimada).';

create or replace function coordinacion.set_contratos_periodos_actividad_updated_at()
returns trigger
language plpgsql
set search_path = coordinacion
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_contratos_periodos_actividad_updated_at on coordinacion.contratos_periodos_actividad;
create trigger set_contratos_periodos_actividad_updated_at
before update on coordinacion.contratos_periodos_actividad
for each row
execute function coordinacion.set_contratos_periodos_actividad_updated_at();

alter table coordinacion.contratos_periodos_actividad enable row level security;
grant select, insert, update, delete on coordinacion.contratos_periodos_actividad to authenticated;

drop policy if exists "contratos_periodos_actividad_can_read" on coordinacion.contratos_periodos_actividad;
create policy "contratos_periodos_actividad_can_read"
on coordinacion.contratos_periodos_actividad
for select
to authenticated
using (coordinacion.can_access_coordinacion_contrato(contrato_id));

drop policy if exists "contratos_periodos_actividad_can_write" on coordinacion.contratos_periodos_actividad;
create policy "contratos_periodos_actividad_can_write"
on coordinacion.contratos_periodos_actividad
as permissive
for all
to authenticated
using (coordinacion.can_manage_coordinacion_contrato(contrato_id))
with check (coordinacion.can_manage_coordinacion_contrato(contrato_id));

drop policy if exists "coordinacion_solo_usuarios" on coordinacion.contratos_periodos_actividad;
create policy "coordinacion_solo_usuarios"
on coordinacion.contratos_periodos_actividad
as restrictive
for all
to authenticated
using ((select coordinacion.is_coordinacion_user()))
with check ((select coordinacion.is_coordinacion_user()));

-- Lugar de consulta de los documentos del anexo (apartado 13): la sede de la empresa.
update coordinacion.empresas
set lugar_consulta_documentos = 'En la sede de la empresa'
where lugar_consulta_documentos is null or btrim(lugar_consulta_documentos) = '';
