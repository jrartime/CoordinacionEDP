-- ============================================================================
--  Preparaciones de facturacion: calculo guardado y versionado, y su vinculo
--  con los registros (horas) que lo componen y con la factura real emitida.
-- ----------------------------------------------------------------------------
--  Requiere contratos_facturacion.sql, contratos_funciones_servicio.sql,
--  registros.sql y coordinacion_contrato_id_sets.sql.
--
--  Una preparacion es un "Calcular" guardado de la pestaña Preparacion de
--  facturas: fija que registros entraron, con que tarifa, y el total
--  resultante. Volver a calcular el mismo contrato+agrupacion+periodo no pisa
--  la anterior: la sustituye dejando rastro (estado 'anulada', sustituye_a),
--  igual que nominas.emitir_nomina.
--
--  Granularidad (contratos_facturacion_preparaciones.servicio_ids/funcion_id):
--    servicio_ids vacio/null   -> el contrato completo (todos los servicios)
--    servicio_ids con 1+ ids   -> un grupo de servicios, todas sus funciones
--                                  juntas (caso normal: una factura por
--                                  servicio). Puede haber varios ids porque
--                                  una funcion compartida entre servicios los
--                                  fusiona (ver contratos_funciones_servicio.sql):
--                                  esos servicios se agrupan siempre juntos,
--                                  las horas no se reparten entre ellos.
--    servicio_ids + funcion_id -> una funcion separada dentro de su(s) servicio(s)
--
--  Una factura nunca cruza contratos: contrato_id es unico y obligatorio.
-- ============================================================================

create table if not exists public.contratos_facturacion_preparaciones (
  id bigint generated by default as identity primary key,
  contrato_id integer not null references public.contratos (id) on update cascade on delete restrict,
  servicio_ids bigint[],
  funcion_id integer references public.funciones (id) on update cascade on delete restrict,
  fecha_desde date not null,
  fecha_hasta date not null,
  estado text not null default 'vigente',
  sustituye_a bigint references public.contratos_facturacion_preparaciones (id) on update cascade on delete set null,
  anulada_motivo text,
  anulada_en timestamptz,
  contrato_facturacion_id bigint references public.contratos_facturacion (id) on update cascade on delete set null,
  base_imponible numeric(14, 2) not null default 0,
  iva numeric(14, 2) not null default 0,
  total numeric(14, 2) not null default 0,
  horas_diurnas numeric(10, 2) not null default 0,
  horas_nocturnas numeric(10, 2) not null default 0,
  observacion text,
  generada_por_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint contratos_facturacion_preparaciones_estado_chk
    check (estado in ('vigente', 'anulada')),
  constraint contratos_facturacion_preparaciones_rango_chk
    check (fecha_hasta >= fecha_desde),
  constraint contratos_facturacion_preparaciones_funcion_requiere_servicio_chk
    check (funcion_id is null or coalesce(array_length(servicio_ids, 1), 0) > 0)
);

comment on table public.contratos_facturacion_preparaciones is
  'Calculo de "Preparacion de facturas" guardado y congelado. Volver a calcular el mismo contrato+agrupacion+periodo no pisa la anterior: queda anulada (sustituye_a) y la nueva la referencia, con rastro completo. estado: vigente = la version actual; anulada = reemplazada al regenerar o anulada a mano (conserva sus lineas como historico).';
comment on column public.contratos_facturacion_preparaciones.servicio_ids is
  'Vacio/nulo = preparacion de todo el contrato. Con ids = preparacion de ese grupo de servicios (todas sus funciones, salvo que funcion_id tambien se informe). Normalizado (distinct, ordenado) para poder comparar por igualdad al detectar regeneraciones.';
comment on column public.contratos_facturacion_preparaciones.contrato_facturacion_id is
  'Factura real a la que dio lugar esta preparacion, cuando existe. Nulo mientras solo es un calculo guardado (fase de "crear factura desde preparacion" pendiente).';

create table if not exists public.contratos_facturacion_lineas (
  id bigint generated by default as identity primary key,
  contrato_id integer not null references public.contratos (id) on update cascade on delete restrict,
  preparacion_id bigint references public.contratos_facturacion_preparaciones (id) on update cascade on delete cascade,
  contrato_facturacion_id bigint references public.contratos_facturacion (id) on update cascade on delete set null,
  registro_id bigint not null references public.registros (id) on update cascade on delete restrict,
  instalacion_id integer references public.instalaciones (id) on update cascade on delete set null,
  funcion_id integer references public.funciones (id) on update cascade on delete set null,
  horas_diurnas numeric(10, 2) not null default 0,
  horas_nocturnas numeric(10, 2) not null default 0,
  precio_01 numeric(14, 4),
  precio_02 numeric(14, 4),
  tipo_precio text,
  importe numeric(14, 2),
  created_at timestamptz not null default now(),
  constraint contratos_facturacion_lineas_origen_chk
    check (preparacion_id is not null or contrato_facturacion_id is not null)
);

comment on table public.contratos_facturacion_lineas is
  'Vinculo atomico registro (jornada) <-> preparacion/factura. Es la trazabilidad que sustituye a registros.factura: por cada registro se sabe en que preparacion y, en su caso, en que factura entro. Un registro solo puede estar "activo" (preparacion vigente o factura real) en una linea a la vez; lo blinda el trigger validate_contratos_facturacion_lineas_unicidad y no un UNIQUE simple, porque el historico de preparaciones anuladas debe conservar sus lineas.';
comment on column public.contratos_facturacion_lineas.importe is
  'Importe de esta linea en el momento de generarse. Nulo en los vinculos migrados desde el antiguo registros.factura, donde no se conserva el desglose por registro.';

