-- ----------------------------------------------------------------------------
--  guardar_preparacion_facturacion: persiste un calculo de "Preparacion de
--  facturas". Si ya existe una preparacion vigente identica (mismo contrato,
--  agrupacion y periodo), exige p_reemplazar=true para regenerar: la anterior
--  queda anulada (con rastro) y la nueva la referencia via sustituye_a.
--  security invoker: el RLS de ambas tablas ya limita a los contratos que el
--  usuario puede gestionar.
-- ----------------------------------------------------------------------------
drop function if exists public.guardar_preparacion_facturacion(
  integer, date, date, jsonb, numeric, numeric, numeric, bigint, integer, boolean, text, numeric, numeric
);

create or replace function public.guardar_preparacion_facturacion(
  p_contrato_id integer,
  p_fecha_desde date,
  p_fecha_hasta date,
  p_lineas jsonb,
  p_base_imponible numeric,
  p_iva numeric,
  p_total numeric,
  p_servicio_ids bigint[] default null,
  p_funcion_id integer default null,
  p_reemplazar boolean default false,
  p_observacion text default null,
  p_horas_diurnas numeric default 0,
  p_horas_nocturnas numeric default 0
)
returns bigint
language plpgsql
volatile
security invoker
set search_path = public
as $$
declare
  v_id bigint;
  v_previa bigint;
  v_previa_facturada boolean;
  v_ajenos integer;
  v_servicio_ids bigint[];
begin
  if p_fecha_desde is null or p_fecha_hasta is null then
    raise exception 'La preparación necesita un periodo (desde y hasta).';
  end if;
  if p_fecha_hasta < p_fecha_desde then
    raise exception 'La fecha hasta no puede ser anterior a la fecha desde.';
  end if;
  if jsonb_typeof(p_lineas) is distinct from 'array' or jsonb_array_length(p_lineas) = 0 then
    raise exception 'La preparación no tiene registros que facturar.';
  end if;

  -- Normalizado (distinct + orden) para que la comparacion de igualdad al
  -- buscar una preparacion previa idéntica sea estable sin importar el orden
  -- en que llegue el array.
  v_servicio_ids := coalesce((
    select array_agg(distinct x order by x)
    from unnest(coalesce(p_servicio_ids, '{}'::bigint[])) as x
    where x is not null
  ), '{}'::bigint[]);
  if array_length(v_servicio_ids, 1) is null then
    v_servicio_ids := null;
  end if;

  if p_funcion_id is not null and v_servicio_ids is null then
    raise exception 'Para separar por función hace falta indicar también el servicio.';
  end if;

  -- Una factura nunca cruza contratos: ningun registro de las lineas puede
  -- facturarse en otro contrato distinto del indicado. Se compara contra el
  -- contrato facturable (propio, salvo redireccion en
  -- registros_facturacion_destino), no contra registros.contrato_id a secas,
  -- para permitir facturar en el contrato B horas trabajadas en el A.
  select count(*) into v_ajenos
  from jsonb_array_elements(p_lineas) as l
  join public.registros r on r.id = (l ->> 'registro_id')::bigint
  left join public.registros_facturacion_destino rfd on rfd.registro_id = r.id
  where coalesce(rfd.contrato_id, r.contrato_id) is distinct from p_contrato_id;

  if v_ajenos > 0 then
    raise exception 'Hay % registro(s) que no pertenecen al contrato indicado.', v_ajenos;
  end if;

  select p.id, p.contrato_facturacion_id is not null
    into v_previa, v_previa_facturada
  from public.contratos_facturacion_preparaciones p
  where p.contrato_id = p_contrato_id
    and coalesce(p.servicio_ids, '{}'::bigint[]) = coalesce(v_servicio_ids, '{}'::bigint[])
    and coalesce(p.funcion_id, 0) = coalesce(p_funcion_id, 0)
    and p.fecha_desde = p_fecha_desde
    and p.fecha_hasta = p_fecha_hasta
    and p.estado = 'vigente';

  if v_previa is not null then
    if not p_reemplazar then
      raise exception 'Ya hay una preparación vigente para este contrato, agrupación y periodo (#%). Regenérala explícitamente para sustituirla.', v_previa;
    end if;
    if v_previa_facturada then
      raise exception 'La preparación #% ya está vinculada a una factura real; no se puede regenerar automáticamente.', v_previa;
    end if;
    update public.contratos_facturacion_preparaciones
    set estado = 'anulada', anulada_en = now(),
        anulada_motivo = coalesce(anulada_motivo, 'Reemplazada al regenerar la preparación')
    where id = v_previa;
  end if;

  insert into public.contratos_facturacion_preparaciones (
    contrato_id, servicio_ids, funcion_id, fecha_desde, fecha_hasta,
    sustituye_a, base_imponible, iva, total, horas_diurnas, horas_nocturnas,
    observacion, generada_por_email
  ) values (
    p_contrato_id, v_servicio_ids, p_funcion_id, p_fecha_desde, p_fecha_hasta,
    v_previa, coalesce(p_base_imponible, 0), coalesce(p_iva, 0), coalesce(p_total, 0),
    coalesce(p_horas_diurnas, 0), coalesce(p_horas_nocturnas, 0),
    p_observacion,
    nullif(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'email', '')
  )
  returning id into v_id;

  insert into public.contratos_facturacion_lineas (
    contrato_id, preparacion_id, registro_id, instalacion_id, funcion_id,
    horas_diurnas, horas_nocturnas, precio_01, precio_02, tipo_precio, importe
  )
  select
    p_contrato_id, v_id,
    (l ->> 'registro_id')::bigint,
    nullif(l ->> 'instalacion_id', '')::integer,
    nullif(l ->> 'funcion_id', '')::integer,
    coalesce((l ->> 'horas_diurnas')::numeric, 0),
    coalesce((l ->> 'horas_nocturnas')::numeric, 0),
    nullif(l ->> 'precio_01', '')::numeric,
    nullif(l ->> 'precio_02', '')::numeric,
    l ->> 'tipo_precio',
    nullif(l ->> 'importe', '')::numeric
  from jsonb_array_elements(p_lineas) as l;

  return v_id;
end;
$$;

