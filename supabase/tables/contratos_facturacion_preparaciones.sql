-- Un registro solo puede estar "activo" (vinculado a una preparacion vigente
-- o a una factura real) en una linea a la vez. Las lineas de preparaciones
-- anuladas no cuentan: quedan como historico, libres para una nueva.
create or replace function public.validate_contratos_facturacion_lineas_unicidad()
returns trigger
language plpgsql
as $$
declare
  v_conflicto record;
begin
  select l.id, l.preparacion_id, l.contrato_facturacion_id
    into v_conflicto
  from public.contratos_facturacion_lineas l
  left join public.contratos_facturacion_preparaciones p on p.id = l.preparacion_id
  where l.registro_id = new.registro_id
    and l.id is distinct from new.id
    and (l.contrato_facturacion_id is not null or p.estado = 'vigente')
  limit 1;

  if found then
    if v_conflicto.contrato_facturacion_id is not null then
      raise exception 'El registro % ya está vinculado a la factura #%.',
        new.registro_id, v_conflicto.contrato_facturacion_id;
    else
      raise exception 'El registro % ya está incluido en la preparación vigente #%.',
        new.registro_id, v_conflicto.preparacion_id;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists validate_contratos_facturacion_lineas_unicidad on public.contratos_facturacion_lineas;
create trigger validate_contratos_facturacion_lineas_unicidad
before insert or update of registro_id, preparacion_id, contrato_facturacion_id
on public.contratos_facturacion_lineas
for each row
execute function public.validate_contratos_facturacion_lineas_unicidad();

