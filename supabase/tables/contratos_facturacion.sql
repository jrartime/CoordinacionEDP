-- Facturacion de contratos: periodos, presupuestos, estados y facturas.
-- Requiere contratos.sql y coordinacion_contrato_id_sets.sql.

create table if not exists public.contratos_estado_facturas (
  id integer generated by default as identity primary key,
  registro integer,
  estado text not null unique,
  descripcion text
);

insert into public.contratos_estado_facturas (id, registro, estado, descripcion)
values
  (1, 1000, 'Remitida', null),
  (2, 1200, 'REC', 'Registrada en el registro electronico REC'),
  (3, 1300, 'RCF', 'Registrada en RCF'),
