-- ============================================================================
-- RD 723/2026, replanteamiento (17/11/2026). Esquema `coordinacion` (proyecto Portal Laboral).
--
-- Sustituye lo que dejó `rd723_condiciones_laborales.sql` (escrito para el esquema `public`
-- antiguo) en lo que ya no encaja con el diseño decidido el 17/11/2026:
--   - Se quita `contratos_rd723`: la distribución irregular se da por persona y de forma
--     particular, se replanteará más adelante; la «tabla salarial» era siempre la A, que va
--     fija en el texto del anexo.
--   - Se quitan de `historiales_laborales_rd723` las columnas de entrega (`medio_entrega`,
--     `fecha_entrega`, `entregado`): un solo «entregado» no sirve cuando un periodo recibe
--     varias entregas. Las sustituye la tabla de entregas.
--   - Se crea `historiales_laborales_anexos_rd723`: una fila por anexo entregado (alta,
--     subrogación, variación, llamamiento o a petición), con la copia exacta de los datos
--     que llevaba, la versión del texto y el recibí firmado. Es la prueba de entrega que pide
--     el art. 6.2 del RD y lo que permite saber qué cambió desde el último anexo.
--
-- Se queda sin tocar: `convenios`, las columnas RD723 de `empresas`, `empresas_documentos` y
-- el resto de `historiales_laborales_rd723` (datos manuales por periodo del anexo).
-- ============================================================================

-- Salvaguarda: solo se borra lo que está vacío.
do $$
begin
  if exists (select 1 from coordinacion.contratos_rd723) then
    raise exception 'contratos_rd723 tiene filas: no se borra.';
  end if;
  if exists (
    select 1 from coordinacion.historiales_laborales_rd723
    where medio_entrega is not null or fecha_entrega is not null or entregado
  ) then
    raise exception 'historiales_laborales_rd723 tiene datos de entrega: no se quitan.';
  end if;
end $$;

drop table if exists coordinacion.contratos_rd723;
drop function if exists coordinacion.set_contratos_rd723_updated_at();

alter table coordinacion.historiales_laborales_rd723
  drop column if exists medio_entrega,
  drop column if exists fecha_entrega,
  drop column if exists entregado;

-- ----------------------------------------------------------------------------
-- Entregas del anexo informativo.
--   historial_id queda a NULL si se borra el periodo (la prueba de entrega no se pierde);
--   personal_id se guarda siempre para poder encontrarla y para el alcance por RLS.
-- ----------------------------------------------------------------------------
create table if not exists coordinacion.historiales_laborales_anexos_rd723 (
  id bigint generated by default as identity primary key,
  personal_id integer not null references coordinacion.personal (id),
  historial_id bigint references coordinacion.historiales_laborales (id) on delete set null,
  tipo text not null check (tipo in ('alta', 'subrogacion', 'variacion', 'llamamiento', 'peticion')),
  convenio_id integer references coordinacion.convenios (id),
  version_texto text not null,
  datos jsonb not null,
  medio_entrega text check (medio_entrega in ('papel', 'electronico')),
  fecha_entrega date,
  recibi_nombre_archivo text,
  recibi_ruta_storage text,
  recibi_tipo_mime text,
  recibi_tamano_bytes bigint,
  notas text,
  generado_por uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists historiales_laborales_anexos_rd723_personal_idx
  on coordinacion.historiales_laborales_anexos_rd723 (personal_id, created_at desc);
create index if not exists historiales_laborales_anexos_rd723_historial_idx
  on coordinacion.historiales_laborales_anexos_rd723 (historial_id);

comment on table coordinacion.historiales_laborales_anexos_rd723 is
  'Anexo informativo RD 723/2026 entregado a una persona: tipo, copia exacta de los datos que llevaba (datos), versión del texto, medio y fecha de entrega y recibí firmado (ruta en Storage). Prueba de entrega del art. 6.2.';
comment on column coordinacion.historiales_laborales_anexos_rd723.datos is
  'Copia de los datos con los que se generó el PDF; sirve para comparar con lo que cambie después (llamamientos y variaciones).';
comment on column coordinacion.historiales_laborales_anexos_rd723.fecha_entrega is
  'NULL mientras el anexo está generado pero no entregado.';

create or replace function coordinacion.set_historiales_laborales_anexos_rd723_updated_at()
returns trigger
language plpgsql
set search_path = coordinacion
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_historiales_laborales_anexos_rd723_updated_at
  on coordinacion.historiales_laborales_anexos_rd723;
create trigger set_historiales_laborales_anexos_rd723_updated_at
before update on coordinacion.historiales_laborales_anexos_rd723
for each row
execute function coordinacion.set_historiales_laborales_anexos_rd723_updated_at();

