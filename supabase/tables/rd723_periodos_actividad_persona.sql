-- ============================================================================
-- RD 723/2026: periodos de actividad propios de una persona (esquema `coordinacion`).
--
-- Los periodos de actividad del contrato de servicio (contratos_periodos_actividad) valen para todo el
-- personal fijo-discontinuo de ese contrato. Cuando una persona tiene los suyos, se guardan aquí, por
-- periodo de su historial laboral, y SUSTITUYEN a los del contrato solo para ese periodo.
-- ============================================================================

create table if not exists coordinacion.historiales_laborales_periodos_actividad (
  id bigint generated by default as identity primary key,
  historial_id bigint not null references coordinacion.historiales_laborales (id) on delete cascade,
  personal_id integer not null references coordinacion.personal (id),
  fecha_inicio date not null,
  fecha_fin date not null,
  created_at timestamptz not null default now(),
  constraint historiales_laborales_periodos_actividad_fechas check (fecha_fin >= fecha_inicio)
);

create index if not exists historiales_laborales_periodos_actividad_historial_idx
  on coordinacion.historiales_laborales_periodos_actividad (historial_id, fecha_inicio);

comment on table coordinacion.historiales_laborales_periodos_actividad is
  'Tramos de actividad propios de una persona en un periodo de su historial laboral; sustituyen a los del contrato en el anexo RD 723/2026.';

alter table coordinacion.historiales_laborales_periodos_actividad enable row level security;
grant select, insert, update, delete on coordinacion.historiales_laborales_periodos_actividad to authenticated;

drop policy if exists "historiales_laborales_periodos_actividad_can_read" on coordinacion.historiales_laborales_periodos_actividad;
create policy "historiales_laborales_periodos_actividad_can_read"
on coordinacion.historiales_laborales_periodos_actividad
for select
to authenticated
using (coordinacion.can_access_coordinacion_personal(personal_id));

drop policy if exists "historiales_laborales_periodos_actividad_can_write" on coordinacion.historiales_laborales_periodos_actividad;
create policy "historiales_laborales_periodos_actividad_can_write"
on coordinacion.historiales_laborales_periodos_actividad
as permissive
for all
to authenticated
using (coordinacion.can_manage_coordinacion_historial(personal_id))
with check (coordinacion.can_manage_coordinacion_historial(personal_id));

drop policy if exists "coordinacion_solo_usuarios" on coordinacion.historiales_laborales_periodos_actividad;
create policy "coordinacion_solo_usuarios"
on coordinacion.historiales_laborales_periodos_actividad
as restrictive
for all
to authenticated
using ((select coordinacion.is_coordinacion_user()))
with check ((select coordinacion.is_coordinacion_user()));
