-- ============================================================================
-- Mensajes prediseñados de WhatsApp para el personal
-- ----------------------------------------------------------------------------
-- Los usa el panel "WhatsApp" de la ficha de Personal (CoordinacionEDP y
-- portal-laboral comparten esta tabla). Se pueden usar {{nombre}} y
-- {{nombre_completo}}, que el frontend sustituye por los de la persona.
--   Lectura:   quien tenga la pestaña Personal.
--   Escritura: quien pueda gestionar Personal.
-- ============================================================================

create table if not exists coordinacion.whatsapp_plantillas (
  id bigint generated by default as identity primary key,
  titulo text not null check (length(btrim(titulo)) > 0),
  texto text not null check (length(btrim(texto)) > 0),
  orden integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table coordinacion.whatsapp_plantillas is
  'Mensajes prediseñados para enviar por WhatsApp desde la ficha de Personal. Admiten {{nombre}} y {{nombre_completo}}.';

create or replace function coordinacion.set_whatsapp_plantillas_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists set_whatsapp_plantillas_updated_at on coordinacion.whatsapp_plantillas;
create trigger set_whatsapp_plantillas_updated_at
before update on coordinacion.whatsapp_plantillas
for each row
execute function coordinacion.set_whatsapp_plantillas_updated_at();

alter table coordinacion.whatsapp_plantillas enable row level security;

grant select, insert, update, delete on coordinacion.whatsapp_plantillas to authenticated;
grant usage, select on sequence coordinacion.whatsapp_plantillas_id_seq to authenticated;

drop policy if exists "whatsapp_plantillas_can_read" on coordinacion.whatsapp_plantillas;
create policy "whatsapp_plantillas_can_read"
on coordinacion.whatsapp_plantillas
for select
to authenticated
using (coordinacion.can_access_coordinacion_pestana('personal'));

drop policy if exists "whatsapp_plantillas_can_insert" on coordinacion.whatsapp_plantillas;
create policy "whatsapp_plantillas_can_insert"
on coordinacion.whatsapp_plantillas
for insert
to authenticated
with check (coordinacion.can_manage_coordinacion_personal());

drop policy if exists "whatsapp_plantillas_can_update" on coordinacion.whatsapp_plantillas;
create policy "whatsapp_plantillas_can_update"
on coordinacion.whatsapp_plantillas
for update
to authenticated
using (coordinacion.can_manage_coordinacion_personal())
with check (coordinacion.can_manage_coordinacion_personal());

drop policy if exists "whatsapp_plantillas_can_delete" on coordinacion.whatsapp_plantillas;
create policy "whatsapp_plantillas_can_delete"
on coordinacion.whatsapp_plantillas
for delete
to authenticated
using (coordinacion.can_manage_coordinacion_personal());

-- ============================================================================
-- Historial de mensajes abiertos por WhatsApp desde la ficha de Personal.
-- Se registra al abrir el chat con el texto escrito (WhatsApp no confirma el
-- envío real). Sin update ni delete: es un registro.
-- ============================================================================
create table if not exists coordinacion.whatsapp_envios (
  id bigint generated by default as identity primary key,
  personal_id integer not null references coordinacion.personal (id) on delete cascade,
  texto text not null,
  telefono text,
  plantilla_titulo text,
  enviado_por uuid default auth.uid(),
  enviado_por_nombre text,
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_envios_personal_idx
on coordinacion.whatsapp_envios (personal_id, created_at desc);

create or replace function coordinacion.set_whatsapp_envios_autor()
returns trigger
language plpgsql
security definer
set search_path = coordinacion, public
as $$
begin
  new.enviado_por := coalesce(new.enviado_por, auth.uid());
  if new.enviado_por_nombre is null then
    select cu.nombre into new.enviado_por_nombre
    from coordinacion.coordinacion_usuarios cu
    where cu.user_id = new.enviado_por;
  end if;
  return new;
end;
$$;

drop trigger if exists set_whatsapp_envios_autor on coordinacion.whatsapp_envios;
create trigger set_whatsapp_envios_autor
before insert on coordinacion.whatsapp_envios
for each row execute function coordinacion.set_whatsapp_envios_autor();

alter table coordinacion.whatsapp_envios enable row level security;
grant select, insert on coordinacion.whatsapp_envios to authenticated;
grant usage, select on sequence coordinacion.whatsapp_envios_id_seq to authenticated;

drop policy if exists "whatsapp_envios_can_read" on coordinacion.whatsapp_envios;
create policy "whatsapp_envios_can_read"
on coordinacion.whatsapp_envios for select to authenticated
using (coordinacion.can_access_coordinacion_pestana('personal'));

drop policy if exists "whatsapp_envios_can_insert" on coordinacion.whatsapp_envios;
create policy "whatsapp_envios_can_insert"
on coordinacion.whatsapp_envios for insert to authenticated
with check (coordinacion.can_manage_coordinacion_personal());
