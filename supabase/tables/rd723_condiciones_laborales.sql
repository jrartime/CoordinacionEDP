create table if not exists public.historiales_laborales_rd723 (
  historial_id bigint primary key references public.historiales_laborales (id) on delete cascade,
  periodo_actividad_estimado text,
  periodo_inactividad_estimado text,
  duracion_estimada_periodo_actividad text,
  jornada_anual_estimada_horas numeric,
  horas_complementarias_pct numeric,
