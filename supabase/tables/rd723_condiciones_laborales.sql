-- ============================================================================
-- RD 723/2026 (condiciones laborales transparentes y previsibles): modelo de
-- datos para poder generar el anexo informativo obligatorio por contrato,
-- llamamiento o variacion. Fase "solo BD" (ver memoria rd723-condiciones-
-- laborales-anexo): esto NO crea todavia ningun formulario ni PDF, solo deja
-- el sitio donde vivira cada dato.
--
-- El anexo modelo (18 apartados) se cruzo con lo que ya existe en la app:
--   - Puesto, funciones, centros de trabajo, horario, salario jornada
--     completa, tipo de contratacion -> ya en `puestos`/`contratos`/
--     `contrato_instalaciones`/`historiales_laborales`, no se toca aqui.
--   - Convenio como entidad legal (codigo BOE, jornada maxima, periodo de
--     prueba, vacaciones, preavisos) -> no existia, se crea `convenios`.
--   - Mutua, Plan de Igualdad, protocolos de acoso/LGTBI, sistemas
--     algoritmicos -> son por EMPRESA (EDP/INTECA), no por contrato: columnas
--     nuevas en `empresas`.
--   - Periodos estimados de actividad/inactividad, % horas complementarias,
--     medio de llamamiento, entrega del anexo -> cambian en cada llamamiento/
--     alta: tabla nueva 1:1 `historiales_laborales_rd723`, para no meter 10
--     columnas mas en `historiales_laborales` (tabla ya grande y usada por el
--     motor de nominas).
--   - Distribucion irregular de jornada, si aplica -> es una politica del
--     contrato de servicio: tabla nueva 1:1 `contratos_rd723`.
--
-- Tabla A/B salarial del IV Convenio de Ocio educativo (art. 44): decision
-- expresa del usuario (23/09/2026) de NO modelar la dualidad en
-- `convenios_categorias_salarios` -- EDP usa la Tabla A en todos sus
-- contratos actuales. `contratos_rd723.tabla_salarial` queda como campo
-- informativo de texto para el anexo, sin ningun efecto en el calculo de
-- nominas.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Convenios (entidad legal). convenios_categorias.convenio ya guardaba el
--    nombre repetido en ~20 filas; se normaliza sin borrar esa columna
--    (mismo patron de retirada en 2 fases que "servicio": BD primero, UI
--    despues, borrado del duplicado al final).
-- ----------------------------------------------------------------------------

create table if not exists public.convenios (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  codigo text,
  boe_numero text,
  boe_fecha date,
  fecha_publicacion date,
  vigente_hasta date,
  articulo_prorroga text,
  jornada_maxima_anual_horas numeric,
  jornada_maxima_semanal_horas numeric,
  periodo_prueba_texto text,
  vacaciones_dias integer,
  vacaciones_notas text,
  preaviso_llamamiento_dias integer,
  preaviso_llamamiento_articulo text,
  preaviso_cese_dias integer,
  preaviso_cese_notas text,
  notas text,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.convenios is
  'Convenio colectivo como entidad legal (codigo BOE, vigencia, jornada maxima, periodo de prueba, vacaciones, preavisos). convenios_categorias.convenio_id referencia esta tabla; convenios_categorias.convenio (texto) se mantiene por compatibilidad con la UI actual.';
comment on column public.convenios.preaviso_cese_dias is
  'Preaviso general de cese voluntario en dias, cuando el convenio no lo diferencia por grupo profesional. Si varia por grupo, dejar NULL y detallarlo en preaviso_cese_notas (ver V Convenio Instalaciones Deportivas, art. 17.3: grupos 1-2 dos meses, grupos 3-5 quince dias).';

