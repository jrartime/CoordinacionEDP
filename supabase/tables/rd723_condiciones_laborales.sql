  llamamiento_medio text,
  llamamiento_contacto text,
  formacion_obligatoria_texto text,
  medio_entrega text check (medio_entrega in ('papel', 'electronico')),
  fecha_entrega date,
  entregado boolean not null default false,
  notas text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.historiales_laborales_rd723 is
